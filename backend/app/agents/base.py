from __future__ import annotations

import logging
from typing import Any

from app.config import settings
from app.schemas import AgentRequest
from app.services.llm import LLMError, llm_client


logger = logging.getLogger(__name__)


class BaseTacticalAgent:
    agent_id: str
    display_name: str
    system_prompt: str
    llm_editable_fields: set[str] = {"activity"}

    async def respond(
        self,
        request: AgentRequest,
        grounded_result: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Use the configured LLM while preserving a deterministic response contract.

        The grounded result is generated by local tactical rules first. It is also
        supplied to the model so map facts and message IDs remain stable. Missing
        top-level keys are backfilled from the grounded result.
        """

        if not llm_client.configured:
            return {**grounded_result, "source": "mock"}

        try:
            llm_result = await llm_client.generate_json(
                system_prompt=self.system_prompt,
                payload={
                    "agent": self.agent_id,
                    "request": request.model_dump(),
                    "grounded_result": grounded_result,
                },
            )
            merged = dict(grounded_result)
            for field in self.llm_editable_fields:
                if field in llm_result:
                    merged[field] = llm_result[field]
            merged.update(
                {
                    "source": "llm",
                    "model": settings.llm_model,
                    "llm_narrative": {
                        key: value
                        for key, value in llm_result.items()
                        if key not in grounded_result
                    },
                }
            )
            return merged
        except LLMError:
            logger.exception("%s LLM call failed", self.display_name)
            if settings.llm_fallback_to_mock:
                return {
                    **grounded_result,
                    "source": "mock-fallback",
                    "warning": "LLM unavailable; deterministic tactical fallback used.",
                }
            raise
